// BEEA: a small PDF that echoes the request

export async function mockBeeaReport(payload: Values, flowTitle: string): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  let page = doc.addPage([595, 842]);
  let y = 790;

  const line = (text: string, opts: { size?: number; f?: typeof font; color?: [number, number, number]; indent?: number } = {}) => {
    const size = opts.size ?? 10;
    if (y < 60) {
      page = doc.addPage([595, 842]);
      y = 790;
    }
    page.drawText(winAnsi(text), {
      x: 50 + (opts.indent ?? 0),
      y,
      size,
      font: opts.f ?? font,
      color: rgb(...(opts.color ?? [0.1, 0.12, 0.16])),
    });
    y -= size + 6;
  };

  page.drawRectangle({ x: 0, y: 812, width: 595, height: 30, color: rgb(0.86, 0.15, 0.15) });
  page.drawText("MOCK REPORT - NOT GENERATED BY SLEB", { x: 50, y: 822, size: 11, font: bold, color: rgb(1, 1, 1) });

  line(`BEEA ${flowTitle} - Building Energy Efficiency Assessment`, { size: 16, f: bold });
  line(`Generated ${new Date().toISOString().slice(0, 10)} in demo mode (SLEB_MOCK=1).`, { color: [0.4, 0.45, 0.5] });
  y -= 8;
  line("This placeholder confirms the form, validation and PDF viewer work end to end.", {});
  line("The live API returns the official report here once it is reachable.", {});
  y -= 12;

  const walk = (obj: Values, depth: number) => {
    for (const [k, v] of Object.entries(obj)) {
      if (v && typeof v === "object" && !Array.isArray(v)) {
        y -= 4;
        line(k, { f: bold, size: depth === 0 ? 12 : 11, indent: depth * 14 });
        walk(v as Values, depth + 1);
      } else {
        line(`${k}: ${Array.isArray(v) ? v.join(", ") : String(v)}`, { indent: depth * 14 });
      }
    }
  };
  line("Submitted data", { size: 13, f: bold });
  walk(payload, 0);

  return doc.save();
}

