function higherIsBetter(name: string, unit?: string) {
  if (/Loss|Waste|Leak|Defect|Boil/i.test(name)) return false;
  if (name === "RefrigerationCOP" || name === "RefineryComplexityIndex") return true;
  return unit === "%";
}

function round(n: number, digits = 2) {
  return String(+n.toFixed(digits));
}

function bench(value: number, higher: boolean) {
  const bat = higher ? Math.min(100, value * 1.12) : value * 0.82;
  const onTrack = higher ? value >= bat : value <= bat;
  return { bat, result: onTrack ? "On Track" : "Needs Improvement" };
}

export function mockIeeaResult(payload: Values, existing: boolean): IeeaResult {
  const bi = (getPath(payload, "BuildingData.BuildingInfo") ?? {}) as Values;
  const industry = String(bi.IndustryType) as Industry;
  const production = Number(bi.MonthlyProduction) || 1;
  const systems = ((getPath(payload, "BuildingData.SystemTypes") as string[]) ?? []).map(
    (l) => SYSTEM_TYPES[l as SystemLabel]
  );
  const kpiDefs = INDUSTRY_KPIS[industry] ?? [];
  const kpiInput = (bi.FacilityKPIs ?? {}) as Values;

  // Totals
  let energy: number;
  const cons = (bi.Consumption ?? {}) as Values;
  if (existing) {
    energy = 12 * Object.entries(GJ_PER_UNIT).reduce((s, [k, f]) => s + (Number(cons[k]) || 0) * f, 0);
  } else {
    energy = production * 12 * 2.5;
  }
  const carbon = energy * 0.075 + (Number(cons.MonthlyOtherConsumption) || 0) * 12 * (Number(cons.OtherEnergyEF) || 0);

  // KPIs
  const KPIBenchmarking: Record<string, unknown> = {};
  for (const [name, label, unit, , sample] of kpiDefs) {
    const value = Number(existing ? kpiInput[name] : sample) || Number(sample);
    const { bat, result } = bench(value, higherIsBetter(name, unit));
    KPIBenchmarking[name] = round(value);
    KPIBenchmarking[`${name}OfBAT`] = round(bat);
    KPIBenchmarking[`${name}BenchmarkingResult`] = result;
    KPIBenchmarking[`${name}Recommendation`] =
      result === "On Track" ? "-" : [`Close the gap to BAT on ${label} with targeted upgrades`];
  }
  const primary = kpiDefs[0];
  const sec = primary ? Number(KPIBenchmarking[primary[0]]) : 0;
  const secBat = primary ? Number(KPIBenchmarking[`${primary[0]}OfBAT`]) : 0;

  // Systems
  const SystemPerformanceBenchmarking: Record<string, Record<string, unknown>> = {};
  const EnergyAnalysisAndRecommendation: Record<string, unknown> = {};
  let totalSavings = 0;
  const share = systems.length ? 0.7 / systems.length : 0;
  systems.forEach((key, i) => {
    const sys = (getPath(payload, `BuildingData.${key}`) ?? {}) as Values;
    const [metric, bat, higher] = SYSTEM_BENCH[key];
    const raw = existing && sys[metric] !== undefined ? sys[metric] : TYPICAL_BASELINE[metric];
    const onTrack =
      typeof bat === "string" ? String(raw) >= bat : higher ? Number(raw) >= bat : Number(raw) <= bat;
    SystemPerformanceBenchmarking[key] = {
      [metric]: String(raw),
      [`${metric}OfBAT`]: String(bat),
      BenchmarkingResult: onTrack ? "On Track" : "Needs Improvement",
    };
    const measured = Number(sys.EnergyConsumptionMeasured);
    let consumption = measured > 0 ? measured * (key === "Boilers" ? 1 : 0.0036) : energy * share;
    if (key === "RenewableGeneration") consumption = -Math.abs(consumption);
    const savings = Math.abs(consumption) * (onTrack ? 0.05 : 0.18 + (i % 3) * 0.04);
    if (key !== "RenewableGeneration" && key !== "ConstructionSiteEnergy") totalSavings += savings;
    EnergyAnalysisAndRecommendation[key] = {
      EnergyConsumption: round(consumption),
      Recommendation: SYSTEM_RECS[key],
      EnergySavings: round(savings),
    };
  });
  EnergyAnalysisAndRecommendation.TotalEnergySavings = round(totalSavings);

  const water = existing ? (Number(cons.MonthlyWaterConsumption) || 0) * 12 : production * 12 * 6.5;
  const raw = existing ? (Number(cons.MonthlyRawMaterialConsumption) || 0) * 12 : 0;

  return {
    TotalEnergyConsumption: round(energy),
    TotalCarbonEmission: round(carbon),
    SpecificEnergyConsumptionBenchmarking: primary
      ? {
          SEC: round(sec),
          SECOfBAT: round(secBat),
          SECUnit: primary[2] ?? "",
          SECBenchmarkingResult: String(KPIBenchmarking[`${primary[0]}BenchmarkingResult`]),
        }
      : null,
    KPIBenchmarking,
    SystemPerformanceBenchmarking,
    EnergyAnalysisAndRecommendation,
    WaterAnalysisAndRecommendation: water
      ? {
          WaterConsumption: round(water),
          WaterRecommendation: ["Recover cooling tower blowdown and process water for reuse"],
          TotalWaterSavings: round(water * 0.15),
        }
      : null,
    RawMaterialAnalysisAndRecommendation: raw
      ? {
          RawMaterialConsumption: round(raw),
          RawMaterialRecommendation: ["Improve process yield and material recovery"],
          TotalRawMaterialSavings: round(raw * 0.02),
        }
      : null,
  };
}
